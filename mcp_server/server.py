@mcp.tool()
def search(query: str) -> str:
    """
    Real-time internet search tool.

    The LLM is responsible for understanding the user's intent
    and generating the appropriate search query.

    This MCP server does NOT rewrite, classify, or modify
    the user's search query.

    The received query is sent directly to Tavily.

    Args:
        query: Search query generated by the LLM.

    Returns:
        Formatted Tavily search results.
    """

    cleaned_query = (query or "").strip()

    if not cleaned_query:
        return "No search query provided."

    tavily_key = os.getenv("TAVILY_API_KEY", "")

    if not tavily_key:
        return (
            "Sorry, search service is not configured "
            "(missing TAVILY_API_KEY)."
        )

    url = "https://api.tavily.com/search"

    # --------------------------------------------------------
    # IMPORTANT:
    # Do NOT modify the query here.
    #
    # Example:
    #
    # LLM -> "latest IPL winner"
    # MCP -> "latest IPL winner"
    # Tavily -> search
    #
    # LLM -> "IPL 2023 winner"
    # MCP -> "IPL 2023 winner"
    # Tavily -> search
    # --------------------------------------------------------

    provider_query = cleaned_query

    try:
        print(
            f"MCP search query -> {provider_query}",
            file=sys.stderr,
        )
    except Exception:
        pass

    # --------------------------------------------------------
    # TAVILY PAYLOAD
    # --------------------------------------------------------

    payload = {
        "api_key": tavily_key,
        "query": provider_query,
        "search_depth": "advanced",
        "max_results": 5,
        "include_answer": True,
    }

    try:
        print(
            "MCP search payload -> "
            + json.dumps(
                {
                    key: value
                    for key, value in payload.items()
                    if key != "api_key"
                }
            ),
            file=sys.stderr,
        )

    except Exception:
        pass

    # --------------------------------------------------------
    # CALL TAVILY
    # --------------------------------------------------------

    try:
        request = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers={
                "Content-Type": "application/json",
            },
            method="POST",
        )

        with urllib.request.urlopen(
            request,
            timeout=15,
        ) as response:

            data = json.loads(
                response.read().decode("utf-8")
            )

    except Exception as e:
        return f"Error executing search: {str(e)}"

    # --------------------------------------------------------
    # EXTRACT RESPONSE
    # --------------------------------------------------------

    results = data.get("results") or []

    answer = str(
        data.get("answer") or ""
    ).strip()

    try:
        print(
            f"MCP search answer -> {answer}",
            file=sys.stderr,
        )

        for index, item in enumerate(
            results[:5],
            start=1,
        ):
            title = str(
                item.get("title", "")
            ).strip()

            source_url = str(
                item.get("url", "")
            ).strip()

            print(
                f"MCP search result {index} -> "
                f"{title} | {source_url}",
                file=sys.stderr,
            )

    except Exception:
        pass

    if not results and not answer:
        return (
            "No relevant search results found "
            "for this query."
        )

    # --------------------------------------------------------
    # FORMAT RESPONSE
    # --------------------------------------------------------

    sections = []

    if answer:
        sections.append(
            f"Tavily Summary:\n{answer}"
        )

    if results:

        result_lines = [
            "Search Results:"
        ]

        for index, item in enumerate(
            results[:5],
            start=1,
        ):

            title = str(
                item.get("title", "")
            ).strip()

            content = str(
                item.get("content", "")
            ).strip()

            source_url = str(
                item.get("url", "")
            ).strip()

            if len(content) > 280:
                content = (
                    content[:280]
                    .rstrip()
                    + "..."
                )

            result_lines.extend(
                [
                    f"Result {index}",
                    f"Title: {title}",
                    f"Content: {content}",
                    f"Source: {source_url}",
                    "",
                ]
            )

        sections.append(
            "\n".join(
                result_lines
            ).strip()
        )

    return "\n\n".join(
        section
        for section in sections
        if section
    ).strip()


