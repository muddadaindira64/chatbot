# ============================================================

@mcp.tool()
def weather(
    city: str,
    date: str = "",
) -> str:
    """
    Get weather information for a city.

    Args:
        city: Name of the city.
        date: Optional date
              (today, tomorrow, yesterday, YYYY-MM-DD).

    Returns:
        Weather report.
    """

    if not city:
        return "Please specify a city name."

    try:

        # ----------------------------------------------------
        # GEOCODING
        # ----------------------------------------------------

        geo_url = (
            "https://geocoding-api.open-meteo.com/v1/search?"
            f"name={urllib.parse.quote(city)}"
            "&count=1"
            "&language=en"
            "&format=json"
        )

        request = urllib.request.Request(
            geo_url
        )

        with urllib.request.urlopen(
            request,
            timeout=10,
        ) as response:

            geo_response = json.loads(
                response.read().decode("utf-8")
            )

        if (
            "results" not in geo_response
            or not geo_response["results"]
        ):
            return f"Cannot find location: {city}"

        location = geo_response["results"][0]

        lat = location["latitude"]
        lon = location["longitude"]

        # ----------------------------------------------------
        # CURRENT WEATHER
        # ----------------------------------------------------

        if not date:

            weather_url = (
                "https://api.open-meteo.com/v1/forecast?"
                f"latitude={lat}"
                f"&longitude={lon}"
                "&current="
                "temperature_2m,"
                "apparent_temperature,"
                "relative_humidity_2m,"
                "precipitation,"
                "weather_code,"
                "wind_speed_10m"
                "&timezone=auto"
            )

            request = urllib.request.Request(
                weather_url
            )

            with urllib.request.urlopen(
                request,
                timeout=10,
            ) as response:

                weather_response = json.loads(
                    response.read().decode("utf-8")
                )

            current = weather_response["current"]

            return f"""
Current weather in {city}:

Temperature: {current['temperature_2m']} C
Feels like: {current['apparent_temperature']} C
Humidity: {current['relative_humidity_2m']}%
Precipitation: {current['precipitation']} mm
Wind Speed: {current['wind_speed_10m']} km/h
Weather Code: {current['weather_code']}
""".strip()

        # ----------------------------------------------------
        # DATE-BASED WEATHER
        # ----------------------------------------------------

        today_date = datetime.date.today()

        requested_date = (
            date.lower().strip()
        )

        if requested_date == "today":

            target_date = today_date

        elif requested_date == "tomorrow":

            target_date = (
                today_date
                + datetime.timedelta(days=1)
            )

        elif requested_date == "yesterday":

            target_date = (
                today_date
                - datetime.timedelta(days=1)
            )

        else:

            try:

                target_date = (
                    datetime.datetime.strptime(
                        date,
                        "%Y-%m-%d",
                    ).date()
                )

            except ValueError:

                return (
                    "Invalid date format. "
                    "Use today, tomorrow, "
                    "yesterday, or YYYY-MM-DD."
                )

        target_date_str = (
            target_date.isoformat()
        )

        if target_date < today_date:

            base_url = (
                "https://archive-api.open-meteo.com/v1/archive"
            )

        else:

            base_url = (
                "https://api.open-meteo.com/v1/forecast"
            )

        daily_url = (
            f"{base_url}?"
            f"latitude={lat}"
            f"&longitude={lon}"
            f"&start_date={target_date_str}"
            f"&end_date={target_date_str}"
            "&daily="
            "temperature_2m_max,"
            "temperature_2m_min,"
            "precipitation_sum,"
            "precipitation_probability_max,"
            "weather_code"
            "&timezone=auto"
        )

        request = urllib.request.Request(
            daily_url
        )

        with urllib.request.urlopen(
            request,
            timeout=10,
        ) as response:

            weather_response = json.loads(
                response.read().decode("utf-8")
            )

        if "daily" not in weather_response:

            return (
                f"No weather data available "
                f"for {city} on {target_date_str}."
            )

        daily = weather_response["daily"]

        max_temp = daily[
            "temperature_2m_max"
        ][0]

        min_temp = daily[
            "temperature_2m_min"
        ][0]

        precipitation = daily[
            "precipitation_sum"
        ][0]

        weather_code = daily[
            "weather_code"
        ][0]

        rain_prob = daily.get(
            "precipitation_probability_max"
        )

        if (
            rain_prob
            and rain_prob[0] is not None
        ):
            rain_text = (
                f"{rain_prob[0]}%"
            )
        else:
            rain_text = "Not available"

        return f"""
Weather in {city} on {target_date_str}:

Maximum Temperature: {max_temp} C
Minimum Temperature: {min_temp} C
Rain Probability: {rain_text}
Precipitation: {precipitation} mm
Weather Code: {weather_code}
""".strip()

    except Exception as e:

        return (
            f"Error fetching weather: {str(e)}"
        )


